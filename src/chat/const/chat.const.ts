/**
 * 두 사람 사이의 방을 유일하게 식별하는 열쇠를 만든다.
 *
 * 왜 필요한가
 *   A가 B에게 말을 걸고, 동시에 B도 A에게 말을 걸면 **방이 두 개** 생긴다.
 *   그러면 A가 보낸 말이 B의 방에는 없다. 각자 다른 방에 대고 말하게 된다.
 *
 *   "이미 방이 있는지 먼저 조회하고 없으면 만든다"만으로는 못 막는다.
 *   두 요청이 동시에 오면 둘 다 '없음'을 보고 둘 다 만든다.
 *   그래서 이 값에 **DB 유니크 제약**을 걸어, 두 번째 저장을 DB가 거절하게 한다.
 *
 * 항상 작은 id 를 앞에 둔다. (3,7) 과 (7,3) 이 같은 열쇠 '3:7' 이 되어야 하기 때문이다.
 */
export function makePairKey(userIdA: number, userIdB: number): string {
    return userIdA < userIdB ? `${userIdA}:${userIdB}` : `${userIdB}:${userIdA}`;
}
