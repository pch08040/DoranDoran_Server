import { IsInt } from 'class-validator';

/** 이 사람과 이야기를 시작한다. (시안: 상대방 프로필 하단 "이야기를 시작하세요!") */
export class CreateRoomDto {
    /**
     * 말을 걸 상대의 id.
     *
     * 방 번호가 아니라 **사람 번호**를 받는 이유
     *   앱은 이 사람과 방이 이미 있는지 없는지 모른다. 알 필요도 없다.
     *   "이 사람과 이야기하고 싶다"만 말하면 서버가 있으면 찾아주고 없으면 만든다.
     *   앱이 먼저 조회해서 없으면 만들도록 하면 요청이 2번 나가고,
     *   그 사이에 상대도 같은 일을 하면 방이 두 개 생긴다.
     */
    @IsInt({ message: '상대방 정보가 올바르지 않아요.' })
    targetUserId: number;
}
